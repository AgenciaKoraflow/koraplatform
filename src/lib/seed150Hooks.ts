export async function seed150Hooks(workspaceId: string) {
  try {
    const { createClient } = await import("@supabase/supabase-js");
    const supabaseUrl = import.meta.env.VITE_SUPABASE_URL;
    const supabaseKey = import.meta.env.VITE_SUPABASE_ANON_KEY;

    if (!supabaseUrl || !supabaseKey) {
      throw new Error("Supabase credentials not found");
    }

    const supabase = createClient(supabaseUrl, supabaseKey);

    // Delete existing hooks
    await supabase.from("hooks").delete().eq("workspace_id", workspaceId);

    // Insert new hooks
    const { error } = await supabase.from("hooks").insert(
      hooks150.map((hook) => ({
        workspace_id: workspaceId,
        text: hook.text,
        template: hook.template,
        pain_point: hook.pain_point,
        emotional_trigger: hook.emotional_trigger,
        creator: hook.creator,
        creator_handle: hook.creator_handle,
        type: hook.type,
        niche: hook.niche,
        content_type: hook.content_type,
        views: Math.floor(Math.random() * 5000) + 1000,
        times_used: Math.floor(Math.random() * 20),
      }))
    );

    if (error) throw error;

    return {
      success: true,
      count: hooks150.length,
      message: `${hooks150.length} hooks foram importados com sucesso!`,
    };
  } catch (error) {
    console.error("Erro ao fazer seed dos hooks:", error);
    throw error;
  }
}
